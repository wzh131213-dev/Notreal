import os
import re
import json
import requests
import math
import numpy as np

class AICodeGenerator:
    """
    AI Code Generator: Takes a natural language video description prompt,
    analyzes its style and motion requirements, and generates Python code
    that renders a high-quality cinematic AI-style video.
    Supports external LLM API call (e.g. OpenAI) or built-in procedural code generation engine.
    """

    def __init__(self, api_key: str = None, api_url: str = None):
        self.api_key = api_key or os.getenv("OPENAI_API_KEY")
        self.api_url = api_url or os.getenv("OPENAI_API_BASE", "https://api.openai.com/v1/chat/completions")

    def generate_code(self, prompt: str, width: int = 1280, height: int = 720, duration: float = 4.0, fps: int = 30) -> str:
        """Attempts to call LLM if key is present, otherwise uses built-in code synthesizer."""
        if self.api_key:
            return self.generate_code_with_llm(prompt, width, height, duration, fps)
        return self.synthesize_code(prompt, width, height, duration, fps)

    def generate_code_with_llm(self, prompt: str, width: int = 1280, height: int = 720, duration: float = 4.0, fps: int = 30) -> str:
        """Calls LLM API to generate Python video rendering code."""
        system_prompt = f"""You are an expert Graphics Programmer and AI Video Code Generator.
Write executable Python code using numpy, PIL (Pillow), cv2 (OpenCV), and moviepy to generate a cinematic video clip based on the user's prompt.

Requirements for the generated code:
1. Must define a function `render_video(output_path, width={width}, height={height}, duration={duration}, fps={fps})`.
2. The video must look like a high-end AI generated video (cinematic lighting, particle dynamics, camera motion, smooth color gradients, depth effects).
3. The function must save the result as an MP4 video at `output_path`.
4. Output ONLY pure, valid Python code inside ```python ``` block without extra prose.
5. Use smooth animation formulas dependent on time `t` (0 <= t <= duration) or frame index.
"""
        user_prompt = f"Generate Python video rendering code for prompt: '{prompt}'. Width: {width}, Height: {height}, Duration: {duration}s, FPS: {fps}."

        try:
            headers = {"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"}
            payload = {
                "model": os.getenv("OPENAI_MODEL", "gpt-4o"),
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt}
                ],
                "temperature": 0.7
            }
            res = requests.post(self.api_url, json=payload, headers=headers, timeout=20)
            if res.status_code == 200:
                content = res.json()["choices"][0]["message"]["content"]
                match = re.search(r'```python\s*(.*?)\s*```', content, re.DOTALL)
                if match:
                    return match.group(1).strip()
                return content.strip()
        except Exception as e:
            print(f"LLM API call failed ({e}). Falling back to procedural AI Code Synthesizer.")

        return self.synthesize_code(prompt, width, height, duration, fps)

    def synthesize_code(self, prompt: str, width: int = 1280, height: int = 720, duration: float = 4.0, fps: int = 30) -> str:
        """
        Synthesizes executable Python code tailored specifically to the prompt semantics.
        The generated code builds real cinematic visual animation with numpy/OpenCV/PIL.
        """
        prompt_clean = prompt.replace('"', '\\"').replace("'", "\\'")
        prompt_lower = prompt.lower()

        # Analyze scene type & visual elements
        if any(k in prompt_lower for k in ["cyberpunk", "neon", "city", "future", "sci-fi", "matrix", "synthwave"]):
            theme = "cyberpunk"
        elif any(k in prompt_lower for k in ["space", "galaxy", "nebula", "star", "cosmic", "universe", "planet"]):
            theme = "cosmic"
        elif any(k in prompt_lower for k in ["ocean", "sea", "wave", "water", "beach", "sunset", "nature", "landscape"]):
            theme = "nature_ocean"
        elif any(k in prompt_lower for k in ["fire", "explosion", "spark", "magic", "energy", "portal", "flame"]):
            theme = "energy_portal"
        elif any(k in prompt_lower for k in ["3d", "cube", "sphere", "geometry", "abstract", "shape", "morph"]):
            theme = "abstract_3d"
        else:
            theme = "cinematic_ai_art"

        code = f'''# AI-Generated Video Code for Prompt: "{prompt_clean}"
# Generated by AI Video Code Synthesizer Engine
import numpy as np
import cv2
import math

def render_video(output_path, width={width}, height={height}, duration={duration}, fps={fps}):
    """
    Renders an AI-style video with prompt-matched parametric procedural shaders,
    particle dynamics, camera dolly/zoom, volumetric lighting, and color grading.
    Prompt: {prompt_clean}
    Theme: {theme}
    """
    total_frames = int(duration * fps)
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(output_path, fourcc, fps, (width, height))

    np.random.seed(42)
    num_particles = 180
    particles = np.random.rand(num_particles, 4) # x, y, speed_z, size
    particles[:, 0] *= width
    particles[:, 1] *= height
    particles[:, 2] = particles[:, 2] * 2 + 0.5
    particles[:, 3] = particles[:, 3] * 4 + 2

    prompt_str = "{prompt_clean}"
    theme_name = "{theme}"

    for frame in range(total_frames):
        t = frame / total_frames
        time_sec = frame / fps

        # Base Canvas initialization
        img = np.zeros((height, width, 3), dtype=np.uint8)

        # Camera Zoom / Dolly effect (1.0 -> 1.15)
        cam_zoom = 1.0 + 0.15 * math.sin(t * math.pi * 0.8)
        cam_pan_x = math.sin(t * math.pi * 2) * 20
        cam_pan_y = math.cos(t * math.pi * 1.5) * 10

        if theme_name == "cyberpunk":
            y_indices, x_indices = np.indices((height, width))
            center_x = width / 2 + cam_pan_x
            center_y = height / 2 + cam_pan_y

            r = np.clip(15 + 40 * (y_indices / height) + 30 * math.sin(t * 3), 0, 255)
            g = np.clip(5 + 20 * (x_indices / width), 0, 255)
            b = np.clip(35 + 80 * (y_indices / height) + 50 * math.cos(t * 2), 0, 255)
            img[:, :, 0] = b.astype(np.uint8)
            img[:, :, 1] = g.astype(np.uint8)
            img[:, :, 2] = r.astype(np.uint8)

            horizon = int(height * 0.55)
            for i in range(-15, 16):
                x_start = int(center_x + i * 30)
                x_end = int(center_x + i * 180 * cam_zoom)
                cv2.line(img, (x_start, horizon), (x_end, height), (255, 0, 180), 1, cv2.LINE_AA)

            for j in range(12):
                grid_y = int(horizon + (height - horizon) * (((j + t * 4) % 12) / 12) ** 2)
                cv2.line(img, (0, grid_y), (width, grid_y), (0, 230, 255), 1, cv2.LINE_AA)

            sun_center = (int(center_x), horizon - 30)
            cv2.circle(img, sun_center, int(80 * cam_zoom), (0, 140, 255), -1, cv2.LINE_AA)
            cv2.circle(img, sun_center, int(85 * cam_zoom), (255, 0, 200), 2, cv2.LINE_AA)

        elif theme_name == "cosmic":
            y_i, x_i = np.indices((height, width))
            cx, cy = width / 2 + cam_pan_x, height / 2 + cam_pan_y
            dist = np.sqrt((x_i - cx)**2 + (y_i - cy)**2) / (width * 0.5)
            angle = np.arctan2(y_i - cy, x_i - cx) + t * 2.5 - dist * 3.0

            spiral = np.sin(angle * 3) * 0.5 + 0.5
            nebula_r = np.clip((1.0 - dist) * 180 * spiral + 20 * math.sin(t * 4), 0, 255)
            nebula_g = np.clip((1.0 - dist) * 80 * (1 - spiral) + 30, 0, 255)
            nebula_b = np.clip((1.0 - dist) * 230 + 40, 0, 255)

            img[:, :, 0] = np.clip(nebula_b, 0, 255).astype(np.uint8)
            img[:, :, 1] = np.clip(nebula_g, 0, 255).astype(np.uint8)
            img[:, :, 2] = np.clip(nebula_r, 0, 255).astype(np.uint8)

            core_r = int(60 * cam_zoom + 10 * math.sin(t * 6))
            cv2.circle(img, (int(cx), int(cy)), core_r, (255, 240, 220), -1, cv2.LINE_AA)
            cv2.circle(img, (int(cx), int(cy)), int(core_r * 1.5), (255, 180, 100), 3, cv2.LINE_AA)

        elif theme_name == "nature_ocean":
            y_i, x_i = np.indices((height, width))
            sunset_y = height * 0.45

            sky_factor = np.clip(y_i / sunset_y, 0, 1)
            sky_r = 255 * (1 - sky_factor * 0.4)
            sky_g = 120 * (1 - sky_factor * 0.7) + 30 * math.sin(t * 2)
            sky_b = 60 + sky_factor * 80

            ocean_mask = y_i > sunset_y
            wave = np.sin(x_i * 0.03 + y_i * 0.05 + t * 6) * 15
            wave_highlight = np.sin(x_i * 0.1 - t * 8) * 40

            b_channel = np.where(ocean_mask, np.clip(120 + wave + wave_highlight, 0, 255), sky_b)
            g_channel = np.where(ocean_mask, np.clip(60 + wave * 0.5, 0, 255), sky_g)
            r_channel = np.where(ocean_mask, np.clip(180 + wave_highlight, 0, 255), sky_r)

            img[:, :, 0] = b_channel.astype(np.uint8)
            img[:, :, 1] = g_channel.astype(np.uint8)
            img[:, :, 2] = r_channel.astype(np.uint8)

            sun_y = int(sunset_y - 20 * (1 - t * 0.3))
            cv2.circle(img, (int(width / 2 + cam_pan_x), sun_y), int(70 * cam_zoom), (100, 220, 255), -1, cv2.LINE_AA)

            for ly in range(int(sunset_y), height, 6):
                ref_w = int((ly - sunset_y) * 0.8 + 20 + math.sin(ly * 0.2 + t * 5) * 15)
                ref_x1 = max(0, int(width / 2 + cam_pan_x - ref_w / 2))
                ref_x2 = min(width, int(width / 2 + cam_pan_x + ref_w / 2))
                if ref_x2 > ref_x1:
                    img[ly:ly+3, ref_x1:ref_x2, :] = cv2.addWeighted(img[ly:ly+3, ref_x1:ref_x2, :], 0.5, np.full((3, ref_x2 - ref_x1, 3), (120, 220, 255), dtype=np.uint8), 0.5, 0)

        elif theme_name == "energy_portal":
            y_i, x_i = np.indices((height, width))
            cx, cy = width / 2 + cam_pan_x, height / 2 + cam_pan_y
            dist = np.sqrt((x_i - cx)**2 + (y_i - cy)**2)

            ring = np.exp(-((dist - 180 * cam_zoom) ** 2) / 800)
            portal_val = ring * 255

            img[:, :, 0] = np.clip(portal_val * 0.2 + 20, 0, 255).astype(np.uint8)
            img[:, :, 1] = np.clip(portal_val * 0.8 + 10, 0, 255).astype(np.uint8)
            img[:, :, 2] = np.clip(portal_val * 1.0 + 30, 0, 255).astype(np.uint8)

            for wave_r in range(3):
                cur_r = int(((t * 300 + wave_r * 120) % 360) * cam_zoom)
                cv2.circle(img, (int(cx), int(cy)), cur_r, (0, 255, 200), max(1, int(4 * (1 - cur_r/360))), cv2.LINE_AA)

        else:
            cx, cy = width / 2 + cam_pan_x, height / 2 + cam_pan_y
            y_i, x_i = np.indices((height, width))

            d1 = np.sqrt((x_i - (cx + math.sin(t * 3) * 120))**2 + (y_i - (cy + math.cos(t * 2) * 80))**2)
            d2 = np.sqrt((x_i - (cx - math.sin(t * 2) * 140))**2 + (y_i - (cy - math.cos(t * 3) * 90))**2)

            v1 = np.clip(255 - d1 * 0.8, 0, 255)
            v2 = np.clip(255 - d2 * 0.8, 0, 255)

            img[:, :, 0] = np.clip(v1 * 0.9 + 40, 0, 255).astype(np.uint8)
            img[:, :, 1] = np.clip(v2 * 0.7 + v1 * 0.3, 0, 255).astype(np.uint8)
            img[:, :, 2] = np.clip(v2 * 0.9 + 30, 0, 255).astype(np.uint8)

        # Draw Particle System
        for i in range(num_particles):
            px = (particles[i, 0] + math.sin(t * 3 + i) * 30 + cam_pan_x) % width
            py = (particles[i, 1] - time_sec * 40 * particles[i, 2]) % height
            psize = max(1, int(particles[i, 3] * cam_zoom))

            alpha = 0.5 + 0.5 * math.sin(t * 6 + i)
            p_color = (int(200 * alpha), int(230 * alpha), 255)
            cv2.circle(img, (int(px), int(py)), psize, p_color, -1, cv2.LINE_AA)

        # Title Overlay
        overlay = img.copy()
        cv2.rectangle(overlay, (40, height - 90), (width - 40, height - 30), (10, 10, 15), -1)
        cv2.addWeighted(overlay, 0.4, img, 0.6, 0, img)

        display_text = f"AI Prompt: {{prompt_str}}"
        if len(display_text) > 75:
            display_text = display_text[:72] + "..."

        cv2.putText(img, display_text, (60, height - 52), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (240, 240, 250), 1, cv2.LINE_AA)
        cv2.putText(img, f"Rendered via AI Generated Code | t={{t:.2f}}s", (60, height - 38), cv2.FONT_HERSHEY_SIMPLEX, 0.4, (0, 220, 255), 1, cv2.LINE_AA)

        # Vignette
        vignette_mask = np.ones((height, width), dtype=np.float32)
        cv2.circle(vignette_mask, (width // 2, height // 2), int(max(width, height) * 0.65), 0.5, -1)
        vignette_mask = cv2.GaussianBlur(vignette_mask, (101, 101), 0)
        for c in range(3):
            img[:, :, c] = np.clip(img[:, :, c] * vignette_mask, 0, 255).astype(np.uint8)

        out.write(img)

    out.release()
    print(f"Successfully generated video at: {{output_path}}")

if __name__ == "__main__":
    render_video("output_test.mp4")
'''
        return code
